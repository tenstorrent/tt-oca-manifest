/**
 * @file
 * @brief Include the generated build configuration and refuse a bad one.
 *
 * Every compile-time setting of the library comes from oca_config.h, which
 * lib/scripts/gen_config.py generates from a TOML configuration file and the
 * build places on the include path. lib/oca_config.toml is the default; see
 * INTEGRATION.md, "Configuring the build".
 *
 * The generator already validates the configuration. These guards repeat what
 * the library depends on: a header not generated, generated by another version
 * of the library, missing a setting, holding a switch other than 0 or 1, or
 * combining settings no build can use fails the compile. They also refuse the
 * settings' former -D forms, so a stale override fails loudly instead of being
 * ignored.
 *
 * They do not tie the header to its configuration file. A header edited by
 * hand into another valid configuration compiles, as does one left behind
 * when the file changed; `gen_config.py --check` is what finds either.
 *
 * This is an internal header — it is not part of the public library API.
 */

#ifndef OCA_CONFIG_CHECK_H
#define OCA_CONFIG_CHECK_H

#if defined(OCA_SUPPORT_CLASSIC) || defined(OCA_SUPPORT_PQC)
#error "OCA_SUPPORT_CLASSIC and OCA_SUPPORT_PQC are set by [variants] classic / pqc in the build configuration file, not with -D"
#endif
#if defined(OCA_TOC_MAX_IMAGES)
#error "OCA_TOC_MAX_IMAGES is set by [limits] toc_max_images in the build configuration file, not with -D"
#endif
#if defined(OCA_RECHECK_SECURITY_VERSION)
#error "OCA_RECHECK_SECURITY_VERSION is set by [hardening] recheck_security_version in the build configuration file, not with -D"
#endif

#include "oca_config.h"

#if !defined(OCA_CFG_FORMAT)
#error "oca_config.h was not generated by lib/scripts/gen_config.py"
#elif OCA_CFG_FORMAT != 1
#error "oca_config.h was generated for another version of this library; regenerate it with this library's lib/scripts/gen_config.py"
#endif

#ifndef OCA_CFG_PORTFOLIO_DIGEST
#error "oca_config.h is missing OCA_CFG_PORTFOLIO_DIGEST; regenerate it"
#endif

#ifndef OCA_CFG_PORTFOLIO_ID
#error "oca_config.h is missing OCA_CFG_PORTFOLIO_ID; regenerate it"
#endif

#ifndef OCA_CFG_VARIANT_CLASSIC
#error "oca_config.h is missing OCA_CFG_VARIANT_CLASSIC; regenerate it"
#endif
#ifndef OCA_CFG_VARIANT_PQC
#error "oca_config.h is missing OCA_CFG_VARIANT_PQC; regenerate it"
#endif
#ifndef OCA_CFG_TOC_MAX_IMAGES
#error "oca_config.h is missing OCA_CFG_TOC_MAX_IMAGES; regenerate it"
#endif
#ifndef OCA_CFG_RECHECK_SECURITY_VERSION
#error "oca_config.h is missing OCA_CFG_RECHECK_SECURITY_VERSION; regenerate it"
#endif
#ifndef OCA_CFG_SECURE_BOOT_DISABLED
#error "oca_config.h is missing OCA_CFG_SECURE_BOOT_DISABLED; regenerate it"
#endif
#ifndef OCA_CFG_HASH_SHA2_256
#error "oca_config.h is missing OCA_CFG_HASH_SHA2_256; regenerate it"
#endif
#ifndef OCA_CFG_SIG_RSA_3072_PKCS1V15_SHA256
#error "oca_config.h is missing OCA_CFG_SIG_RSA_3072_PKCS1V15_SHA256; regenerate it"
#endif
#ifndef OCA_CFG_SIG_ECDSA_P256_SHA256
#error "oca_config.h is missing OCA_CFG_SIG_ECDSA_P256_SHA256; regenerate it"
#endif
#ifndef OCA_CFG_SIG_ML_DSA_87
#error "oca_config.h is missing OCA_CFG_SIG_ML_DSA_87; regenerate it"
#endif
#ifndef OCA_CFG_DER_RSA_PUBLIC_KEY
#error "oca_config.h is missing OCA_CFG_DER_RSA_PUBLIC_KEY; regenerate it"
#endif
#ifndef OCA_CFG_DER_ECDSA_SIGNATURE
#error "oca_config.h is missing OCA_CFG_DER_ECDSA_SIGNATURE; regenerate it"
#endif
#ifndef OCA_CFG_CIPHER_AES_128_CBC
#error "oca_config.h is missing OCA_CFG_CIPHER_AES_128_CBC; regenerate it"
#endif
#ifndef OCA_CFG_CIPHER_AES_256_CBC
#error "oca_config.h is missing OCA_CFG_CIPHER_AES_256_CBC; regenerate it"
#endif
#ifndef OCA_CFG_KDF_SP800_108_HMAC_SHA256
#error "oca_config.h is missing OCA_CFG_KDF_SP800_108_HMAC_SHA256; regenerate it"
#endif
#ifndef OCA_CFG_KEY_SOURCE_PRESHARED
#error "oca_config.h is missing OCA_CFG_KEY_SOURCE_PRESHARED; regenerate it"
#endif

/**
 * @brief Whether a true/false setting holds 0 or 1.
 *
 * A switch holding anything else would read as on in one preprocessor test
 * and off in a comparison elsewhere. Undefined again once the checks below
 * have used it.
 */
#define OCA_CFG_IS_SWITCH(value) ((value) == 0 || (value) == 1)
#if !OCA_CFG_IS_SWITCH(OCA_CFG_VARIANT_CLASSIC) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_VARIANT_PQC) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_RECHECK_SECURITY_VERSION) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_SECURE_BOOT_DISABLED) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_HASH_SHA2_256) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_SIG_RSA_3072_PKCS1V15_SHA256) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_SIG_ECDSA_P256_SHA256) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_SIG_ML_DSA_87) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_DER_RSA_PUBLIC_KEY) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_DER_ECDSA_SIGNATURE) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_CIPHER_AES_128_CBC) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_CIPHER_AES_256_CBC) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_KDF_SP800_108_HMAC_SHA256) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_KEY_SOURCE_PRESHARED)
#error "oca_config.h holds a true/false setting that is neither 0 nor 1; regenerate it"
#endif
#undef OCA_CFG_IS_SWITCH

#if !OCA_CFG_VARIANT_CLASSIC && !OCA_CFG_VARIANT_PQC
#error "oca_config.h enables no manifest variant; [variants] must enable classic or pqc"
#endif

#if !OCA_CFG_HASH_SHA2_256
#error "oca_config.h enables no hash; every manifest carries a manifest_hash"
#endif

/* A build verifies a signature, or declares that it verifies none and so
 * decrypts nothing: a payload is decrypted only once its manifest's signature
 * verifies. */
#if !OCA_CFG_SECURE_BOOT_DISABLED && !OCA_CFG_SIG_RSA_3072_PKCS1V15_SHA256 \
    && !OCA_CFG_SIG_ECDSA_P256_SHA256 && !OCA_CFG_SIG_ML_DSA_87
#error "oca_config.h enables no signature algorithm without [secure_boot] disabled"
#endif
#if OCA_CFG_SECURE_BOOT_DISABLED && (OCA_CFG_SIG_RSA_3072_PKCS1V15_SHA256 \
    || OCA_CFG_SIG_ECDSA_P256_SHA256 || OCA_CFG_SIG_ML_DSA_87)
#error "oca_config.h declares [secure_boot] disabled but enables a signature algorithm"
#endif
#if OCA_CFG_SECURE_BOOT_DISABLED && (OCA_CFG_CIPHER_AES_128_CBC \
    || OCA_CFG_CIPHER_AES_256_CBC || OCA_CFG_KDF_SP800_108_HMAC_SHA256 \
    || OCA_CFG_KEY_SOURCE_PRESHARED)
#error "oca_config.h declares [secure_boot] disabled but enables payload encryption, which needs a verified signature"
#endif

#if (OCA_CFG_CIPHER_AES_128_CBC || OCA_CFG_CIPHER_AES_256_CBC) \
    != OCA_CFG_KDF_SP800_108_HMAC_SHA256 \
    || OCA_CFG_KDF_SP800_108_HMAC_SHA256 != OCA_CFG_KEY_SOURCE_PRESHARED
#error "oca_config.h enables only part of payload encryption; a cipher, a KDF and a key source go together"
#endif

#if OCA_CFG_SIG_ML_DSA_87 && !OCA_CFG_VARIANT_PQC
#error "oca_config.h enables a PQC signature algorithm without [variants] pqc"
#endif

#if OCA_CFG_TOC_MAX_IMAGES < 1
#error "oca_config.h sets toc_max_images below 1; regenerate it"
#endif

#endif /* OCA_CONFIG_CHECK_H */
