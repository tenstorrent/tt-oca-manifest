/**
 * @file
 * @brief Include the generated build configuration and refuse a bad one.
 *
 * Every compile-time setting of the library comes from oca_config.h, which
 * lib/scripts/gen_config.py generates from a TOML configuration file and the
 * build places on the include path. lib/oca_config.toml is the default; see
 * INTEGRATION.md, "Configuring the build".
 *
 * The generator already validates the configuration. These guards repeat what
 * the library depends on, so a header that was hand-edited, generated by
 * another version of the library, or left stale fails the compile rather than
 * building a library its configuration file does not describe. They also
 * refuse the settings' former -D forms, so a stale override fails loudly
 * instead of being ignored.
 *
 * This is an internal header — it is not part of the public library API.
 */

#ifndef OCA_CONFIG_CHECK_H
#define OCA_CONFIG_CHECK_H

#if defined(OCA_SUPPORT_CLASSIC) || defined(OCA_SUPPORT_PQC)
#error "OCA_SUPPORT_CLASSIC and OCA_SUPPORT_PQC are set by [variants] classic / pqc in the build configuration file, not with -D"
#endif
#if defined(OCA_TOC_MAX_IMAGES)
#error "OCA_TOC_MAX_IMAGES is set by [limits] toc_max_images in the build configuration file, not with -D"
#endif
#if defined(OCA_RECHECK_SECURITY_VERSION)
#error "OCA_RECHECK_SECURITY_VERSION is set by [hardening] recheck_security_version in the build configuration file, not with -D"
#endif

#include "oca_config.h"

#if !defined(OCA_CFG_FORMAT)
#error "oca_config.h was not generated by lib/scripts/gen_config.py"
#elif OCA_CFG_FORMAT != 1
#error "oca_config.h was generated for another version of this library; regenerate it with this library's lib/scripts/gen_config.py"
#endif

#if !defined(OCA_CFG_VARIANT_CLASSIC) || !defined(OCA_CFG_VARIANT_PQC) \
    || !defined(OCA_CFG_TOC_MAX_IMAGES) \
    || !defined(OCA_CFG_RECHECK_SECURITY_VERSION) \
    || !defined(OCA_CFG_HASH_SHA2_256) \
    || !defined(OCA_CFG_SIG_RSA_3072_PKCS1V15_SHA256) \
    || !defined(OCA_CFG_SIG_ECDSA_P256_SHA256) \
    || !defined(OCA_CFG_SIG_ML_DSA_87) \
    || !defined(OCA_CFG_DER_RSA_PUBLIC_KEY) \
    || !defined(OCA_CFG_DER_ECDSA_SIGNATURE) \
    || !defined(OCA_CFG_CIPHER_AES_128_CBC) \
    || !defined(OCA_CFG_CIPHER_AES_256_CBC) \
    || !defined(OCA_CFG_KDF_SP800_108_HMAC_SHA256) \
    || !defined(OCA_CFG_KEY_SOURCE_PRESHARED)
#error "oca_config.h is missing a setting; regenerate it"
#endif

/**
 * @brief Whether a true/false setting holds 0 or 1.
 *
 * A switch holding anything else would read as on in one preprocessor test
 * and off in a comparison elsewhere. Undefined again once the checks below
 * have used it.
 */
#define OCA_CFG_IS_SWITCH(value) ((value) == 0 || (value) == 1)
#if !OCA_CFG_IS_SWITCH(OCA_CFG_VARIANT_CLASSIC) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_VARIANT_PQC) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_RECHECK_SECURITY_VERSION) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_HASH_SHA2_256) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_SIG_RSA_3072_PKCS1V15_SHA256) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_SIG_ECDSA_P256_SHA256) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_SIG_ML_DSA_87) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_DER_RSA_PUBLIC_KEY) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_DER_ECDSA_SIGNATURE) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_CIPHER_AES_128_CBC) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_CIPHER_AES_256_CBC) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_KDF_SP800_108_HMAC_SHA256) \
    || !OCA_CFG_IS_SWITCH(OCA_CFG_KEY_SOURCE_PRESHARED)
#error "oca_config.h holds a true/false setting that is neither 0 nor 1; regenerate it"
#endif
#undef OCA_CFG_IS_SWITCH

#if !OCA_CFG_VARIANT_CLASSIC && !OCA_CFG_VARIANT_PQC
#error "oca_config.h enables no manifest variant; [variants] must enable classic or pqc"
#endif

#if !OCA_CFG_HASH_SHA2_256
#error "oca_config.h enables no hash; every manifest carries a manifest_hash"
#endif

#if !OCA_CFG_SIG_RSA_3072_PKCS1V15_SHA256 && !OCA_CFG_SIG_ECDSA_P256_SHA256 \
    && !OCA_CFG_SIG_ML_DSA_87
#error "oca_config.h enables no signature algorithm"
#endif

#if (OCA_CFG_CIPHER_AES_128_CBC || OCA_CFG_CIPHER_AES_256_CBC) \
    != OCA_CFG_KDF_SP800_108_HMAC_SHA256 \
    || OCA_CFG_KDF_SP800_108_HMAC_SHA256 != OCA_CFG_KEY_SOURCE_PRESHARED
#error "oca_config.h enables only part of payload encryption; a cipher, a KDF and a key source go together"
#endif

#if OCA_CFG_SIG_ML_DSA_87 && !OCA_CFG_VARIANT_PQC
#error "oca_config.h enables a PQC signature algorithm without [variants] pqc"
#endif

#if OCA_CFG_TOC_MAX_IMAGES < 1
#error "oca_config.h sets toc_max_images below 1; regenerate it"
#endif

#endif /* OCA_CONFIG_CHECK_H */
